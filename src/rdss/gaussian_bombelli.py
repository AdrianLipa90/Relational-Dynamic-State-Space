def bombelli_cubic_root_certificate() -> dict[str, int | bool]:
    """Exact Cardano-Bombelli certificate generated by g=2+J."""

    g = minimal_relation_role_gaussian_generator()
    gc = g.conjugate()
    x = g.real + gc.real
    uv = g.norm()
    g3 = g**3
    gc3 = gc**3
    cubic_constant = g3.real + gc3.real

    return {
        "x": x,
        "uv": uv,
        "u3_plus_v3": cubic_constant,
        "cubic_value": x**3 - 3 * uv * x - cubic_constant,
        "u3_real": g3.real,
        "u3_imag": g3.imag,
        "v3_real": gc3.real,
        "v3_imag": gc3.imag,
        "pass": (
            x == 4
            and uv == 5
            and cubic_constant == 4
            and x**3 - 15 * x - 4 == 0
            and g3 == GaussianPair(2, 11)
            and gc3 == GaussianPair(2, -11)
        ),
    }


def gaussian_recurrence_term(n: int) -> GaussianPair:
    """Power g^n; real and imaginary parts obey X[n+2]=4X[n+1]-5X[n]."""

    if isinstance(n, bool) or not isinstance(n, int):
        raise TypeError("n must be an integer")
    if n < 0:
        raise ValueError("n must be non-negative")
    return minimal_relation_role_gaussian_generator() ** n


def gaussian_recurrence_residual(n: int) -> GaussianPair:
    """Residual of g^(n+2) - 4 g^(n+1) + 5 g^n."""

    if isinstance(n, bool) or not isinstance(n, int):
        raise TypeError("n must be an integer")
    if n < 0:
        raise ValueError("n must be non-negative")
    a = gaussian_recurrence_term(n)
    b = gaussian_recurrence_term(n + 1)
    c = gaussian_recurrence_term(n + 2)
    return GaussianPair(
        c.real - 4 * b.real + 5 * a.real,
        c.imag - 4 * b.imag + 5 * a.imag,
    )
