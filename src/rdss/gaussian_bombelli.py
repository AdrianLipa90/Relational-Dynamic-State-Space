from __future__ import annotations

from dataclasses import dataclass

from .existence_chain import relation_roles


@dataclass(frozen=True)
class GaussianPair:
    """Exact integer pair a + b J with J^2 = -I."""

    real: int
    imag: int

    def conjugate(self) -> "GaussianPair":
        return GaussianPair(self.real, -self.imag)

    def __mul__(self, other: "GaussianPair") -> "GaussianPair":
        return GaussianPair(
            self.real * other.real - self.imag * other.imag,
            self.real * other.imag + self.imag * other.real,
        )

    def __pow__(self, exponent: int) -> "GaussianPair":
        if isinstance(exponent, bool) or not isinstance(exponent, int):
            raise TypeError("exponent must be an integer")
        if exponent < 0:
            raise ValueError("exponent must be non-negative")
        result = GaussianPair(1, 0)
        base = self
        n = exponent
        while n:
            if n & 1:
                result = result * base
            base = base * base
            n >>= 1
        return result

    def norm(self) -> int:
        return self.real * self.real + self.imag * self.imag


def minimal_relation_role_gaussian_generator() -> GaussianPair:
    """Minimal positive integral non-real lift of the durable two-role carrier.

    The durable role orbit has cardinality 2. With J^2=-I already derived,
    the minimal positive nonzero integral coefficient on J is the unit 1.
    Up to conjugation this gives 2 + J.
    """

    q = len(relation_roles())
    return GaussianPair(q, 1)


def bombelli_ladder() -> tuple[GaussianPair, GaussianPair, GaussianPair, GaussianPair]:
    """First four exact powers of the minimal generator."""

    g = minimal_relation_role_gaussian_generator()
    return (g, g**2, g**3, g**4)


def collatz_coefficients_from_gaussian_generator() -> tuple[int, int, int]:
    """Return (association divisor, repair unit, dissociation multiplier).

    For g=2+J:
      association divisor = Re(g) = 2
      repair unit         = Im(g) = 1
      dissociation factor = Re(g^2) = 3
    """

    g = minimal_relation_role_gaussian_generator()
    g2 = g**2
    return (g.real, g.imag, g2.real)


def l_constants_from_gaussian_and_root_extension() -> tuple[int, int, int]:
    """Return (L3,L4,L5) using Gaussian source plus TIR root-extension closure.

    L4 = Re(g)
    L5 = N(g)
    L3 = L4 + L5

    The final addition is the existing TIR tetrahedral root-extension closure
    rule; g^4 supplies an independent crosscheck, not the definition of L3.
    """

    g = minimal_relation_role_gaussian_generator()
    l4 = g.real
    l5 = g.norm()
    l3 = l4 + l5
    return (l3, l4, l5)


def gaussian_l_constant_closure_crosscheck() -> dict[str, int | bool]:
    """Exact arithmetic closure linking Bombelli, 3-4-5, L constants and 24."""

    g, g2, g3, g4 = bombelli_ladder()
