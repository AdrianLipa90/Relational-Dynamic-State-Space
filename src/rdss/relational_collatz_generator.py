from __future__ import annotations

from dataclasses import dataclass


@dataclass(frozen=True)
class GaussianPair:
    """Exact a+bJ arithmetic with J^2=-1."""

    real: int
    imag: int

    def __mul__(self, other: "GaussianPair") -> "GaussianPair":
        return GaussianPair(
            self.real * other.real - self.imag * other.imag,
            self.real * other.imag + self.imag * other.real,
        )

    def __pow__(self, exponent: int) -> "GaussianPair":
        if isinstance(exponent, bool) or not isinstance(exponent, int):
            raise TypeError("exponent must be an integer")
        if exponent < 0:
            raise ValueError("negative powers are not used in the integral generator")
        out = GaussianPair(1, 0)
        base = self
        n = exponent
        while n:
            if n & 1:
                out = out * base
            base = base * base
            n >>= 1
        return out

    @property
    def norm(self) -> int:
        return self.real * self.real + self.imag * self.imag

    @property
    def conjugate(self) -> "GaussianPair":
        return GaussianPair(self.real, -self.imag)


@dataclass(frozen=True)
class RelationalCollatzConstants:
    role_count: int
    operator_dimension: int
    nonidentity_dimension: int
    repair_unit: int
    association_divisor: int
    dissociation_multiplier: int
    active_seed: int
    l3: int
    l4: int
    l5: int


def durable_role_count() -> int:
    """Cardinality of the persistent relation-role orbit {N,S}."""

    return 2


def full_operator_dimension(role_count: int | None = None) -> int:
    """Real dimension of End(R^q)=M_q(R)."""

    q = durable_role_count() if role_count is None else int(role_count)
    if q < 1:
        raise ValueError("role_count must be positive")
    return q * q


def nonidentity_operator_dimension(role_count: int | None = None) -> int:
    """Number of real operator directions after removing the identity line."""

    return full_operator_dimension(role_count) - 1


def minimal_universal_repair(role_count: int | None = None) -> int:
    """Minimal constant repair for all non-associable residue classes.

    For dissociation multiplier q^2-1, a single residue-independent repair
    mapping every nonzero class mod q to zero exists iff q=2. In that binary
    case the minimal positive repair is exactly 1.
    """

    q = durable_role_count() if role_count is None else int(role_count)
    if q < 2:
        raise ValueError("role_count must be at least two")
    m = q * q - 1
    candidates = [
        r
        for r in range(1, q + 1)
        if all((m * residue + r) % q == 0 for residue in range(1, q))
    ]
    if not candidates:
        raise ValueError("no residue-independent universal repair exists")
    return min(candidates)


def relational_generator(orientation: int = 1) -> GaussianPair:
    """Primitive integral non-real lift q + orientation*J.

    The durable role multiplicity supplies q=2 and the primitive orientation
    coefficient is a unit ±1. The two choices are conjugates.
    """

    if orientation not in (-1, 1):
        raise ValueError("orientation must be +1 or -1")
    return GaussianPair(durable_role_count(), orientation)


def collatz_coefficients_from_relation_algebra() -> tuple[int, int, int]:
    """Return (association divisor, dissociation multiplier, repair)."""

    q = durable_role_count()
    return (q, nonidentity_operator_dimension(q), minimal_universal_repair(q))


def relational_collatz_step(n: int) -> int:
    """Collatz map generated by the durable binary relation algebra."""

    if isinstance(n, bool) or not isinstance(n, int):
        raise TypeError("n must be an integer")
    if n <= 0:
        raise ValueError("n must be positive")

    divisor, multiplier, repair = collatz_coefficients_from_relation_algebra()
    if n % divisor == 0:
        return n // divisor
    return multiplier * n + repair


def relational_collatz_depth_to_one(seed: int, *, max_steps: int = 10_000) -> int:
    """Exact finite depth for seeds that reach one within max_steps.

    This function makes no global convergence claim.
    """

    if isinstance(seed, bool) or not isinstance(seed, int):
        raise TypeError("seed must be an integer")
    if seed <= 0:
        raise ValueError("seed must be positive")
    if max_steps < 0:
        raise ValueError("max_steps must be non-negative")

    n = seed
    for depth in range(max_steps + 1):
        if n == 1:
            return depth
        if depth == max_steps:
            break
        n = relational_collatz_step(n)
    raise RuntimeError("seed did not reach one within max_steps")


def derived_constants() -> RelationalCollatzConstants:
    """Derive the Collatz coefficients and L3/L4/L5 from one binary core."""

    q = durable_role_count()
    dim = full_operator_dimension(q)
    nonid = dim - 1
    repair = minimal_universal_repair(q)

    generator = relational_generator()
    l4 = q
    l5 = generator.norm

    # Existing TIR root-extension closure rule: L3=L4+L5.
    l3 = l4 + l5

    return RelationalCollatzConstants(
        role_count=q,
        operator_dimension=dim,
        nonidentity_dimension=nonid,
        repair_unit=repair,
        association_divisor=q,
        dissociation_multiplier=nonid,
        active_seed=nonid,
        l3=l3,
        l4=l4,
        l5=l5,
    )


def bombelli_ladder() -> tuple[GaussianPair, GaussianPair, GaussianPair, GaussianPair]:
    """First four powers of the canonical generator 2+J."""

    g = relational_generator()
    return (g, g**2, g**3, g**4)


def cardano_bombelli_coefficients() -> tuple[int, int]:
    """Return (linear, constant) for x^3-linear*x-constant=0.

    For g=2+J and gbar=2-J, x=g+gbar=4 obeys
    x^3-3*N(g)*x-2*Re(g^3)=0.
    """

    g = relational_generator()
    linear = 3 * g.norm
    constant = 2 * (g**3).real
    return (linear, constant)


def exact_generator_sanity() -> bool:
    c = derived_constants()
    g1, g2, g3, g4 = bombelli_ladder()
    return all(
        (
            c.role_count == 2,
            c.operator_dimension == 4,
            c.nonidentity_dimension == 3,
            c.repair_unit == 1,
            c.association_divisor == 2,
            c.dissociation_multiplier == 3,
            c.active_seed == 3,
            (c.l3, c.l4, c.l5) == (7, 2, 5),
            g1 == GaussianPair(2, 1),
            g2 == GaussianPair(3, 4),
            g3 == GaussianPair(2, 11),
            g4 == GaussianPair(-7, 24),
            g1.norm == 5,
            relational_collatz_step(3) == 10,
            relational_collatz_step(10) == 5,
            relational_collatz_depth_to_one(3) == 7,
            cardano_bombelli_coefficients() == (15, 4),
        )
    )
